"""Pure generator functions. Input: the registry. Output: {relative path: bytes}.

Every output is deterministic: sorted keys, stable ordering, trailing newline.
"""
from __future__ import annotations

import json
import re
from typing import Iterable

import yaml

from ..gateway.tokens import DEFAULT_TRUST_DOMAIN, spiffe_id_for
from ..manifest import Manifest, canonical_json, sha256_hex

GENERATOR_VERSION = "membrane-gen/0.1.0"
DEFAULT_PARENT_ID = "spiffe://example.org/spire/agent/k8s_psat/membrane"
AGENT_LABEL = "membrane.io/agent-id"
QUARANTINE_LABEL = "membrane.io/quarantine"
HASH_ANNOTATION = "membrane.io/manifest-sha256"
MANAGED_SUBDIRS = ("opa", "spire", "k8s")
HEADER = "# Generated by `membrane gen` from registry/agents. Do not edit by hand.\n"


class GenerationError(Exception):
    """The registry cannot produce a consistent output set."""


def _json(obj) -> bytes:
    return (json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _yaml(obj) -> bytes:
    return (HEADER + yaml.safe_dump(obj, sort_keys=True, default_flow_style=False, width=1000)).encode("utf-8")


def registry_sha256(reg: dict[str, Manifest]) -> str:
    return sha256_hex(canonical_json({k: m.sha256 for k, m in sorted(reg.items())}))


_DIGEST_RE = re.compile(r"@(sha256:[a-f0-9]{64})$")


def image_digests(m: Manifest) -> list[str]:
    """Allowed image digests for a k8s agent. An image with no valid digest gives an empty list,
    so admission denies every image (fail closed)."""
    match = _DIGEST_RE.search(m.spec["runtime"].get("image") or "")
    return [match.group(1)] if match else []


def k8s_binding(m: Manifest) -> dict | None:
    """The fields that bind a pod to its manifest at admission. None for a non-k8s runtime."""
    rt = m.spec["runtime"]
    if rt["type"] != "k8s":
        return None
    return {"namespace": rt.get("namespace") or "", "service_account": rt.get("service_account") or "",
            "image_digests": image_digests(m)}


def opa_data(reg: dict[str, Manifest]) -> dict:
    manifests = {}
    for aid, m in sorted(reg.items()):
        s = m.spec
        tools = {}
        for t in s["tools"]:
            entry = {"scope": t["scope"], "irreversible": bool(t["irreversible"])}
            if "rate_limit_per_min" in t:
                entry["rate_limit_per_min"] = int(t["rate_limit_per_min"])
            tools[t["name"]] = entry
        manifests[aid] = {
            "sha256": m.sha256, "tier": m.tier, "status": s["status"], "canary": bool(s.get("canary", False)),
            "requires_delegator": bool(s["delegation"]["requires_delegator"]),
            "approval_required_for": sorted(s["approval"]["required_for"]),
            "tools": tools,
        }
        binding = k8s_binding(m)
        if binding is not None:
            manifests[aid]["k8s"] = binding
    return {"membrane": {"manifests": manifests}}


def _k8s(reg: dict[str, Manifest]) -> list[Manifest]:
    out = [m for _, m in sorted(reg.items()) if m.spec["runtime"]["type"] == "k8s"]
    for m in out:
        rt = m.spec["runtime"]
        if not rt.get("namespace") or not rt.get("service_account"):
            raise GenerationError(f"{m.id}: k8s runtime needs namespace and service_account")
    return out


def spire_entries(reg: dict[str, Manifest], parent_id: str, trust_domain: str) -> dict:
    entries, seen = [], {}
    for m in _k8s(reg):
        rt = m.spec["runtime"]
        sid = spiffe_id_for(m, trust_domain)
        if sid in seen:
            raise GenerationError(f"{m.id} and {seen[sid]} share SPIFFE ID {sid}; give each agent its own service account")
        seen[sid] = m.id
        entries.append({
            "spiffe_id": sid, "parent_id": parent_id, "hint": m.id,
            "selectors": [{"type": "k8s", "value": f"ns:{rt['namespace']}"},
                          {"type": "k8s", "value": f"sa:{rt['service_account']}"}],
            "x509_svid_ttl": 3600, "jwt_svid_ttl": 300,
        })
    entries.sort(key=lambda e: e["spiffe_id"])
    return {"entries": entries}


def _agent_selector(agent_id: str) -> dict:
    # Quarantined pods drop out of the agent allow policies. Only the quarantine policy selects them.
    return {"matchLabels": {AGENT_LABEL: agent_id},
            "matchExpressions": [{"key": QUARANTINE_LABEL, "operator": "NotIn", "values": ["true"]}]}


def _meta(name: str, m: Manifest) -> dict:
    return {"name": name, "namespace": m.spec["runtime"]["namespace"],
            "labels": {"app.kubernetes.io/managed-by": "membrane", AGENT_LABEL: m.id},
            "annotations": {HASH_ANNOTATION: m.sha256}}


def has_cilium_policy(m: Manifest) -> bool:
    return bool(m.spec["egress"])


def network_policy(m: Manifest) -> dict:
    """Deny all egress. Cilium adds the FQDN allows and the DNS proxy rule (policies are additive).

    An agent with a Cilium policy gets no DNS allow here. A plain layer 4 allow to port 53 on the
    same peer would make Cilium ignore the layer 7 DNS name rules, so the agent could look up any
    name. An agent with no egress list (no Cilium policy) keeps a DNS allow to kube-dns."""
    egress = []
    if not has_cilium_policy(m):
        egress = [{
            "to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}},
                    "podSelector": {"matchLabels": {"k8s-app": "kube-dns"}}}],
            "ports": [{"protocol": "UDP", "port": 53}, {"protocol": "TCP", "port": 53}],
        }]
    return {
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
        "metadata": _meta(f"membrane-{m.id}-egress", m),
        "spec": {
            "podSelector": _agent_selector(m.id),
            "policyTypes": ["Egress"],
            "egress": egress,
        },
    }


def _fqdn_selector(name: str) -> dict:
    return {"matchPattern": name} if "*" in name else {"matchName": name}


def cilium_egress(m: Manifest) -> dict:
    names = sorted(set(m.spec["egress"]))
    return {
        "apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
        "metadata": _meta(f"membrane-{m.id}-fqdn", m),
        "spec": {
            "endpointSelector": _agent_selector(m.id),
            "egress": [
                {   # DNS through the Cilium DNS proxy. Only the allowed names resolve.
                    "toEndpoints": [{"matchLabels": {"k8s:io.kubernetes.pod.namespace": "kube-system",
                                                     "k8s:k8s-app": "kube-dns"}}],
                    "toPorts": [{"ports": [{"port": "53", "protocol": "ANY"}],
                                 "rules": {"dns": [{"matchPattern": n} for n in names]}}],
                },
                {
                    "toFQDNs": [_fqdn_selector(n) for n in names],
                    "toPorts": [{"ports": [{"port": "443", "protocol": "TCP"}]}],
                },
            ],
        },
    }


def quarantine_policy(namespace: str) -> dict:
    """Selects pods labeled membrane.io/quarantine=true. No rules, so all ingress and egress deny."""
    return {
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
        "metadata": {"name": "membrane-quarantine", "namespace": namespace,
                     "labels": {"app.kubernetes.io/managed-by": "membrane"}},
        "spec": {"podSelector": {"matchLabels": {QUARANTINE_LABEL: "true"}},
                 "policyTypes": ["Ingress", "Egress"]},
    }


COMPONENT_LABEL = "membrane.io/component"


def default_deny_policy(namespace: str) -> dict:
    """Deny egress for every pod in an agent namespace that is not a membrane component.

    The per-agent policies add allows for pods with a registered agent-id label. A pod with no
    label, or with a label that no policy names, then has no egress. Membrane's own pods
    (gateway, OPA) carry membrane.io/component and are out of scope here."""
    return {
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
        "metadata": {"name": "membrane-default-deny-egress", "namespace": namespace,
                     "labels": {"app.kubernetes.io/managed-by": "membrane"}},
        "spec": {"podSelector": {"matchExpressions": [{"key": COMPONENT_LABEL, "operator": "DoesNotExist"}]},
                 "policyTypes": ["Egress"], "egress": []},
    }


def registry_entry(m: Manifest) -> str:
    """One ConfigMap value per agent: compact JSON with sorted keys. The tier is a string,
    so it compares directly with the membrane.io/tier label. A non-k8s agent has no
    namespace, service account, or image digests, so admission denies its pods."""
    entry = {"sha256": m.sha256, "tier": str(m.tier)}
    binding = k8s_binding(m)
    if binding is not None:
        entry.update(binding)
    return json.dumps(entry, sort_keys=True, separators=(",", ":"))


def registry_configmap(reg: dict[str, Manifest]) -> dict:
    return {
        "apiVersion": "v1", "kind": "ConfigMap",
        "metadata": {"name": "membrane-registry", "namespace": "membrane-system",
                     "labels": {"app.kubernetes.io/managed-by": "membrane"}},
        "data": {aid: registry_entry(m) for aid, m in sorted(reg.items()) if m.spec["status"] == "active"},
    }


def generate(reg: dict[str, Manifest], *, parent_id: str = DEFAULT_PARENT_ID,
             trust_domain: str = DEFAULT_TRUST_DOMAIN) -> dict[str, bytes]:
    """Return every output as {path relative to the out dir: bytes}."""
    out: dict[str, bytes] = {
        "opa/data.json": _json(opa_data(reg)),
        "spire/entries.json": _json(spire_entries(reg, parent_id, trust_domain)),
        "k8s/membrane-registry.configmap.yaml": _yaml(registry_configmap(reg)),
    }
    namespaces: set[str] = set()
    for m in _k8s(reg):
        namespaces.add(m.spec["runtime"]["namespace"])
        out[f"k8s/{m.id}.networkpolicy.yaml"] = _yaml(network_policy(m))
        if has_cilium_policy(m):
            out[f"k8s/{m.id}.cilium-egress.yaml"] = _yaml(cilium_egress(m))
    for ns in sorted(namespaces):
        out[f"k8s/quarantine.{ns}.networkpolicy.yaml"] = _yaml(quarantine_policy(ns))
        out[f"k8s/default-deny.{ns}.networkpolicy.yaml"] = _yaml(default_deny_policy(ns))
    return dict(sorted(out.items()))


def managed_files_on_disk(out_dir) -> Iterable[str]:
    from pathlib import Path
    root = Path(out_dir)
    for sub in MANAGED_SUBDIRS:
        d = root / sub
        if d.is_dir():
            for p in sorted(d.rglob("*")):
                if p.is_file():
                    yield p.relative_to(root).as_posix()
